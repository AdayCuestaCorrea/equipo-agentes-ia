/**
 * Embeds demo-site/ into lib/domain/template.generated.ts, so serverless functions get the
 * template as code instead of reading the filesystem at runtime. Runs on predev/prebuild.
 */
import fs from "node:fs";
import path from "node:path";

const dir = path.join(process.cwd(), "demo-site");
const files: Record<string, string> = {};
for (const name of fs.readdirSync(dir).sort()) {
  if (/\.(html|css|svg)$/.test(name)) files[name] = fs.readFileSync(path.join(dir, name), "utf8");
}
const out = `// Generated by scripts/gen-template.ts from demo-site/. Do not edit by hand.
import type { SiteFiles } from "./types";

export const TEMPLATE: SiteFiles = ${JSON.stringify(files, null, 2)};
`;
fs.writeFileSync(path.join(process.cwd(), "lib/domain/template.generated.ts"), out);
console.log(`template.generated.ts: ${Object.keys(files).join(", ")}`);
